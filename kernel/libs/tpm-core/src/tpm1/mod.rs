//! 1.2 器件支持。
//!
//! 与 2.0 路径彼此独立:两者的命令编号、报文标签、响应解析规则各成一套,不共享
//! 协议层的常量与解析器。共用的只有下层设施——字节序与游标(`cursor`)、传输
//! 编排(`xfer`/`tis`)。
//!
//! 本路径不含授权会话。所有需要授权的操作(封装、载入密钥、NV 写)不在这里,
//! 驱动对它们只当管道,不参与报文构造。故这里既没有会话状态机,也没有摘要与
//! HMAC——本模块全程不触碰密码学。
//!
//! 分层:
//!
//!   - `ord`  编号与时长分档(纯函数,全量验证)
//!   - `msg`  报文外壳:请求头拼装、响应外壳校验
//!   - `cmd`  命令拼装:把一条完整请求写进缓冲区
//!   - `rsp`  报文体解析:逐字段取值,替代整块联合体拷贝
//!   - `timeout` 超时/时长的单位修正(纯函数,证明各档恒为正)
//!   - `boot` 引导编排:启动、自检轮询、休眠,挂在传输层之上

pub mod ord;
pub mod msg;
pub mod cmd;
pub mod rsp;
pub mod timeout;
pub mod boot;
